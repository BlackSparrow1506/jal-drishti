const TABLE = { en, hi, mr };

export function makeT(lang) {
  const dict = TABLE[lang] || en;
  return (key, vars) => {
    let s = dict[key] ?? en[key] ?? key;
    if (vars) Object.entries(vars).forEach(([k, v]) => (s = s.replace(`{${k}}`, String(v))));
    return s;
  };
}
